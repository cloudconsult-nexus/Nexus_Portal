#!/usr/bin/env node
// Renders two documents from data, never from hand-typed prose:
//   ROLE_MATRIX.md        — what the system is *supposed* to enforce, read
//                           straight from backend/tests/support/roleMatrix.js
//                           and frontend/src/navConfig.js (the same modules
//                           the test suites import).
//   ROLE_AUDIT_REPORT.md  — what the test suites *actually* observed on their
//                           last run, read from tests/results/*.json.
// Run `scripts/run-role-audit.sh` first (or `npm test` in backend/ and
// frontend/ individually) to produce fresh result JSON before regenerating
// the audit report — this script only reads what's already there.

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');

const { ROLES, ENDPOINT_CHECKS, READ_CHECKS } = await import(path.join(ROOT, 'backend/tests/support/roleMatrix.js'));
const { topNav, onCallProNav, bottomNav } = await import(path.join(ROOT, 'frontend/src/navConfig.js'));
const { ROLE_KEYS, EXPECTED_VISIBLE_LABELS } = await import(path.join(ROOT, 'frontend/tests/support/navMatrix.js'));

const ROLE_LABEL = Object.fromEntries(ROLES.map((r) => [r.key, r.label]));
const NAV_SECTIONS = { 'Nexus Portal': topNav, 'OnCall Pro': onCallProNav, 'Account / Reference': bottomNav };

function mdTable(headers, rows) {
  const line = (cells) => `| ${cells.join(' | ')} |`;
  return [line(headers), line(headers.map(() => '---')), ...rows.map(line)].join('\n');
}

// ── ROLE_MATRIX.md ──────────────────────────────────────────────────────
function renderMenuSection() {
  const rows = [];
  for (const [sectionName, items] of Object.entries(NAV_SECTIONS)) {
    for (const item of items) {
      const visibleFor = ROLE_KEYS.filter((role) => EXPECTED_VISIBLE_LABELS[role][
        sectionName === 'Nexus Portal' ? 'topNav' : sectionName === 'OnCall Pro' ? 'onCallProNav' : 'bottomNav'
      ].includes(item.label));
      rows.push([sectionName, item.label, visibleFor.map((r) => ROLE_LABEL[r]).join(', ')]);
    }
  }
  return mdTable(['Section', 'Menu item', 'Visible to'], rows);
}

function renderCrudSection(capability) {
  const rows = ENDPOINT_CHECKS
    .filter((c) => c.capability === capability)
    .map((c) => [c.area, c.op, `\`${c.method.toUpperCase()} ${c.path}\``, c.allowedRoles.map((r) => ROLE_LABEL[r]).join(', ')]);
  return mdTable(['Area', 'Operation', 'Endpoint', 'Allowed roles'], rows);
}

function renderReadSection() {
  const rows = READ_CHECKS.map((c) => [c.area, c.op, `\`${c.method.toUpperCase()} ${c.path}\``]);
  return mdTable(['Area', 'Operation', 'Endpoint'], rows);
}

const roleMatrixMd = `# Role Permission Matrix

Generated by \`scripts/generate-role-docs.mjs\` from
\`backend/tests/support/roleMatrix.js\` and \`frontend/src/navConfig.js\` /
\`frontend/tests/support/navMatrix.js\` — the same data the automated test
suites (\`backend/tests/roleAudit.test.js\`, \`frontend/tests/navVisibility.test.js\`)
assert against. Do not hand-edit this file; edit the source data and
regenerate instead.

## Roles

${mdTable(['Role', 'Key'], ROLES.map((r) => [r.label, `\`${r.key}\``]))}

Note: "Employee" in the original role-validation request is mapped onto the
system's \`read_only\` role, the lowest-privilege role in the platform
(view-only, no management access). Correct this mapping if a distinct
"Employee" role was actually intended.

## Menu visibility

${renderMenuSection()}

## CRUD permissions

Write/administrative operations. Every role not listed under "Allowed roles"
receives an HTTP 403 from the corresponding endpoint.

${renderCrudSection('crud')}

### Open read access

These endpoints have no role gate — every authenticated role may read them
(results are scoped to the caller's organization subtree where applicable):

${renderReadSection()}

## Report access

${renderCrudSection('reports')}

Additionally, \`GET /report-mappings/visible\` is open to every authenticated
role, filtered per-mapping by that mapping's own \`visible_to_roles\` column
rather than a blanket role check.

## Messaging access

${renderCrudSection('messaging')}

Secure Messaging has no backend endpoint yet — it is nav/permission
scaffolding only (per project convention), so its access control is only
enforced at the menu-visibility layer (\`messagingOnly\`), identical to
Customer Messages' menu gate.
`;

fs.writeFileSync(path.join(ROOT, 'ROLE_MATRIX.md'), roleMatrixMd);
console.log('Wrote ROLE_MATRIX.md');

// ── ROLE_AUDIT_REPORT.md ────────────────────────────────────────────────
function readResults(relPath) {
  const p = path.join(ROOT, relPath);
  if (!fs.existsSync(p)) return null;
  return JSON.parse(fs.readFileSync(p, 'utf8'));
}

const backendResults = readResults('backend/tests/results/backend-role-audit.json');
const frontendResults = readResults('frontend/tests/results/frontend-role-audit.json');

if (!backendResults || !frontendResults) {
  console.error('Missing test result JSON — run scripts/run-role-audit.sh (or `npm test` in backend/ and frontend/) before generating the audit report.');
  process.exit(1);
}

const allResults = [...backendResults.results, ...frontendResults.results];

function summaryByRole() {
  const rows = [];
  for (const role of ROLE_KEYS) {
    const forRole = allResults.filter((r) => r.role === role);
    const passed = forRole.filter((r) => r.pass).length;
    rows.push([ROLE_LABEL[role], String(forRole.length), String(passed), String(forRole.length - passed)]);
  }
  return mdTable(['Role', 'Checks', 'Passed', 'Failed'], rows);
}

function summaryByCapability() {
  const caps = ['menu', 'crud', 'reports', 'messaging'];
  const rows = caps.map((cap) => {
    const forCap = allResults.filter((r) => r.capability === cap);
    const passed = forCap.filter((r) => r.pass).length;
    return [cap, String(forCap.length), String(passed), String(forCap.length - passed)];
  });
  return mdTable(['Capability', 'Checks', 'Passed', 'Failed'], rows);
}

function failureDetail() {
  const failures = allResults.filter((r) => !r.pass);
  if (!failures.length) return '_No failures on this run._';
  return mdTable(
    ['Capability', 'Area', 'Operation', 'Role', 'Expected', 'Actual status'],
    failures.map((r) => [r.capability, r.area, r.op, ROLE_LABEL[r.role] || r.role, r.expectedAllowed ? 'allowed' : 'denied', String(r.status)])
  );
}

const totalChecks = allResults.length;
const totalPassed = allResults.filter((r) => r.pass).length;

const auditReportMd = `# Role Audit Report

Generated by \`scripts/generate-role-docs.mjs\` from the last run of
\`backend/tests/roleAudit.test.js\` and \`frontend/tests/navVisibility.test.js\`
— this is a record of what the running application actually did, not a
hand-typed claim. Re-run \`scripts/run-role-audit.sh\` and regenerate to
refresh.

- Backend suite generated at: ${backendResults.generatedAt}
- Frontend suite generated at: ${frontendResults.generatedAt}
- **${totalPassed} / ${totalChecks} checks passed**

## By role

${summaryByRole()}

## By capability

${summaryByCapability()}

## Failures

${failureDetail()}
`;

fs.writeFileSync(path.join(ROOT, 'ROLE_AUDIT_REPORT.md'), auditReportMd);
console.log('Wrote ROLE_AUDIT_REPORT.md');
